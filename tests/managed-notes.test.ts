test("managed Markdown updates stale generated bytes but never changes user edits",()=>{
 const root=mkdtempSync(join(tmpdir(),"xfs-managed-"));
 const db=join(root,"db.sqlite"),vault=join(root,"vault");
 mkdirSync(vault);
 mkdirSync(join(vault,"X Feed Scraper"));
 const filename=join("X Feed Scraper","example.md");
 try{
  const store=new Store(db);
  assert.equal(writeManagedNote(store,vault,filename,"original generated\n"),"created");
  assert.equal(writeManagedNote(store,vault,filename,"original generated\n"),"unchanged");
  assert.equal(writeManagedNote(store,vault,filename,"new generated\n"),"updated");
  const absolute=join(vault,filename);
  assert.equal(readFileSync(absolute,"utf8"),"new generated\n");
  writeFileSync(absolute,"new generated\nMy annotations\n");
  assert.equal(writeManagedNote(store,vault,filename,"later generated\n"),"conflict");
  assert.equal(readFileSync(absolute,"utf8"),"new generated\nMy annotations\n");
  assert.equal(retireManagedNote(store,vault,filename),"conflict");
  assert.equal(readFileSync(absolute,"utf8"),"new generated\nMy annotations\n");
  store.close();
 }finally{rmSync(root,{recursive:true,force:true});}
});
test("managed generated candidates update after rescoring and retire after approval",()=>{
 const root=mkdtempSync(join(tmpdir(),"xfs-managed-vault-"));
 const db=join(root,"db.sqlite"),vault=join(root,"vault");
 mkdirSync(vault);
 try{
  const fixture=readFixture("./tests/fixtures/posts.json");
  const profile=loadProfile("./profiles/design.json");
  ingest(db,fixture,profile);
  const first=exportToVault(db,vault);
  assert.ok(first.created>0);
  const store=new Store(db);
  const source=store.listSources().find(s=>s.url.startsWith("https://github.com/"))!;
  const shortName=readdirSync(join(vault,"X Feed Scraper","Candidates")).find(name=>
   readFileSync(join(vault,"X Feed Scraper","Candidates",name),"utf8").includes(source.url))!;
  const oldPath=join(vault,"X Feed Scraper","Candidates",shortName);
  const previous=readFileSync(oldPath,"utf8");
  store.updateEvaluation(source.id,{title:"A detailed creative component library",
    description:"A substantial set of reusable creative React and motion components with open-source examples for professional UI.",
    license:"MIT",access:"open_source"},{
    category:"frontend",score:90,confidence:0.93,access:"open_source",
    status:"high_quality",reasons:["Public project license is MIT","Useful code examples"]
  });
  store.close();
  const second=exportToVault(db,vault);
  assert.ok(second.updated>=1,"Expected managed candidate to refresh after metadata changes");
  const current=readFileSync(oldPath,"utf8");
  assert.notEqual(current,previous);
  assert.match(current,/score: 90/);
  assert.match(current,/description:/);
  assert.match(current,/license: "MIT"/);
  const reviewStore=new Store(db);
  reviewStore.review(source.id,"approved","Manually verified");
  reviewStore.close();
  const final=exportToVault(db,vault);
  assert.ok(final.removed>=1);
  assert.equal(existsSync(oldPath),false,"Retired candidate must not remain after approval");
  assert.equal(readdirSync(join(vault,"X Feed Scraper","Approved")).length,1);
 }finally{rmSync(root,{recursive:true,force:true});}
});
test("a new library duplicate retires only machine-generated candidate note",()=>{
 const root=mkdtempSync(join(tmpdir(),"xfs-library-dupes-"));
 const db=join(root,"db.sqlite"),vault=join(root,"vault");
 mkdirSync(vault);
 try{
  const fixture=readFixture("./tests/fixtures/posts.json");
  ingest(db,fixture,loadProfile("./profiles/design.json"));
  exportToVault(db,vault);
  const file=readdirSync(join(vault,"X Feed Scraper","Candidates")).find(name=>
   readFileSync(join(vault,"X Feed Scraper","Candidates",name),"utf8").includes("github.com"))!;
  const absolute=join(vault,"X Feed Scraper","Candidates",file);
  writeFileSync(join(vault,"References.md"),"# References\n- [Drei](https://github.com/pmndrs/drei)\n");
  const result=exportToVault(db,vault);
  assert.ok(result.removed>=1);
  assert.equal(existsSync(absolute),false);
  assert.equal(readFileSync(join(vault,"References.md"),"utf8"),
    "# References\n- [Drei](https://github.com/pmndrs/drei)\n");
 }finally{rmSync(root,{recursive:true,force:true});}
});
test("source API pagination provides stable nonoverlapping windows",()=>{
 const root=mkdtempSync(join(tmpdir(),"xfs-pagination-"));
 const db=join(root,"db.sqlite");
 try{
  const store=new Store(db);
  const profile=loadProfile("./profiles/design.json");
  store.close();
  const inputs=Array.from({length:230},(_,i)=>({
   id:"post"+i,url:"https://x.com/anon/status/"+i,author:"A",username:"a",
   text:"Creative typography example https://example.org/sources/"+i
  }));
  ingest(db,inputs,profile);
  const reopened=new Store(db);
  const a=reopened.listSources(undefined,undefined,100,0);
  const b=reopened.listSources(undefined,undefined,100,100);
  const c=reopened.listSources(undefined,undefined,100,200);
  assert.deepEqual([a.length,b.length,c.length],[100,100,30]);
  assert.equal(new Set([...a,...b,...c].map(s=>s.url)).size,230);
  assert.equal(reopened.listSources(undefined,undefined,100,100000).length,0);
  reopened.close();
 }finally{rmSync(root,{recursive:true,force:true});}
});
